@dataclass
class Band:
    """A height band: everything whose top lands in it shows the same colour."""

    index: int
    z_top: float
    z_bottom: float
    colour: str
    features: list[str]


def height_bands(template: Template, printer: Printer) -> list[Band]:
    """Work out the colour bands implied by the template's heights."""
    base = printer.snap_base(template.card.thickness)
    tops: dict[float, list[str]] = {}
    if template.border.enabled:
        tops.setdefault(round(base + printer.snap_relief(template.border.height), 4), []).append(
            "Border"
        )
    for s in template.slots:
        if s.enabled:
            tops.setdefault(round(base + printer.snap_relief(s.height), 4), []).append(s.name)
    bands = [Band(0, base, 0.0, _palette(template, 0), ["Card"])]
    prev = base
    for i, z in enumerate(sorted(tops), start=1):
        bands.append(Band(i, z, prev, _palette(template, i), tops[z]))
        prev = z
    return bands


def _palette(template: Template, i: int) -> str:
    if i < len(template.palette):
        return template.palette[i]
    return DEFAULT_PALETTE[i % len(DEFAULT_PALETTE)]


@dataclass
class ColourChange:
    layer: int  # 1-based, as in Cura's preview
    z: float
    colour: str
    band: int


def colour_changes(template: Template, printer: Printer) -> list[ColourChange]:
    """Filament swaps needed, skipping bands that reuse the previous colour."""
    bands = height_bands(template, printer)
    changes: list[ColourChange] = []
    for prev, band in zip(bands, bands[1:]):
        if band.colour.lower() != prev.colour.lower():
            changes.append(
                ColourChange(printer.layer_starting_at(band.z_bottom), band.z_bottom, band.colour, band.index)
            )
    return changes


def _round_half_up(x: float) -> int:
    return math.floor(x + 0.5 + 1e-9)


def is_close(a: float, b: float) -> bool:
    return math.isclose(a, b, abs_tol=1e-6)
