def _from_dict(cls, data: dict[str, Any] | None):
    """Build a dataclass from a dict, ignoring unknown keys (forward compatible)."""
    if data is None:
        return cls()
    types = {f.name: f.type for f in fields(cls)}
    out = {}
    for k, v in data.items():
        if k not in types:
            continue
        t = types[k] if isinstance(types[k], str) else getattr(types[k], "__name__", "")
        if t == "float" and isinstance(v, int) and not isinstance(v, bool):
            v = float(v)
        elif t == "int" and isinstance(v, float) and v.is_integer():
            v = int(v)
        out[k] = v
    return cls(**out)


@dataclass
class Card:
    width: float = 54.0
    height: float = 86.0
    thickness: float = 1.2
    corner_radius: float = 3.0
    # Safe area kept clear of text, measured from the card edge.
    padding: float = 3.0


@dataclass
class Border:
    enabled: bool = True
    width: float = 1.2
    # Distance between the card edge and the outside of the border.
    inset: float = 0.0
    height: float = 0.4
    # Also draw a ring of border around the hanging hole.
    around_hole: bool = True


@dataclass
class Hole:
    enabled: bool = False
    diameter: float = 5.0
    position: str = "top-left"
    # Distance from the card edge(s) to the centre of the hole.
    offset: float = 5.5


@dataclass
class Slot:
    """One line (or block) of text on the card.

    ``text`` is a template string: ``{column}`` pulls a value from the data
    row, and filters can be chained, e.g. ``{expression|kanji}``.
    """

    name: str = "Text"
    text: str = ""
    enabled: bool = True
    font: str = "Noto Sans CJK JP:Bold"
    size: float = 8.0  # em size in mm (like CSS font-size)
    height: float = 0.6  # how far the text is raised above the card
    y: float = 40.0  # vertical centre of the text, mm from the top edge
    align: str = "center"
    x_offset: float = 0.0  # from centre (center) or from the padding edge (left/right)
    max_width: float = 0.0  # 0 = card width minus padding
    fit: str = "shrink"
    min_size: float = 3.0
    max_lines: int = 2
    line_spacing: float = 1.15
    letter_spacing: float = 0.0  # extra mm between characters
    # Furigana: render Anki-style ``漢字[かんじ]`` as ruby above the base text.
    ruby: bool = False
    ruby_scale: float = 0.45
    ruby_gap: float = 0.4


@dataclass
class Template:
    name: str = "Untitled"
    card: Card = field(default_factory=Card)
    border: Border = field(default_factory=Border)
    hole: Hole = field(default_factory=Hole)
    slots: list[Slot] = field(default_factory=list)
    # Colours of the height bands, from the card base upwards.
    palette: list[str] = field(default_factory=lambda: list(DEFAULT_PALETTE))
    # Fonts tried, in order, when a slot's font has no glyph for a character.
    fallback_fonts: list[str] = field(
        default_factory=lambda: ["Noto Sans CJK JP:Bold", "DejaVu Sans:Bold"]
    )

    def copy(self) -> Template:
        return copy.deepcopy(self)

    # -- serialisation ---------------------------------------------------
    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        return {"cardsmith": 1, **d}

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Template:
        t = cls(
            name=d.get("name", "Untitled"),
            card=_from_dict(Card, d.get("card")),
            border=_from_dict(Border, d.get("border")),
            hole=_from_dict(Hole, d.get("hole")),
            slots=[_from_dict(Slot, s) for s in d.get("slots", d.get("slot", []))],
        )
        if "palette" in d:
            t.palette = list(d["palette"])
        if "fallback_fonts" in d:
            t.fallback_fonts = list(d["fallback_fonts"])
        return t

    def save(self, path: str | Path) -> None:
        Path(path).write_text(tomli_w.dumps(self.to_dict()), encoding="utf-8")

    @classmethod
    def load(cls, path: str | Path) -> Template:
        return cls.from_dict(tomllib.loads(Path(path).read_text(encoding="utf-8")))


@dataclass
class Printer:
    name: str = "Generic 220 × 220"
    bed_width: float = 220.0
    bed_depth: float = 220.0
    margin: float = 5.0  # keep-out from the bed edge
    gap: float = 4.0  # space between cards
    nozzle: float = 0.4
    layer_height: float = 0.2
    first_layer_height: float = 0.2
    # Thinnest stroke / gap that is expected to print; 0 = nozzle diameter.
    min_feature: float = 0.0
    allow_rotation: bool = True
    max_per_plate: int = 0  # 0 = as many as fit

    @property
    def feature_limit(self) -> float:
        return self.min_feature or self.nozzle

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Printer:
        return _from_dict(cls, d)

    # -- layer maths -----------------------------------------------------
    def snap_base(self, thickness: float) -> float:
        """Snap the card thickness to a whole number of layers."""
        h0, h = self.first_layer_height, self.layer_height
        n = max(1, _round_half_up((thickness - h0) / h) + 1)
        return round(h0 + (n - 1) * h, 4)

    def snap_relief(self, height: float) -> float:
        """Snap a raised height to a whole number of layers (at least one)."""
        h = self.layer_height
        return round(max(1, _round_half_up(height / h)) * h, 4)

    def layers_below(self, z: float) -> int:
        """Number of whole layers printed before height ``z``."""
        h0, h = self.first_layer_height, self.layer_height
        if z <= h0 + 1e-6:
            return 1 if z > 1e-6 else 0
        return 1 + _round_half_up((z - h0) / h)

    def layer_starting_at(self, z: float) -> int:
        """1-based layer number (as shown in Cura's preview) that starts at ``z``."""
        return self.layers_below(z) + 1


